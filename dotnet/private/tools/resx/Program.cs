// Compiles `.resx` files to `.resources` with the SDK's own GenerateResource
// task. `resx cultures` prints the culture list in cultures.bzl.

using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.Json;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

internal sealed class Request
{
    /// Microsoft.Build.Tasks.Core.dll from the SDK.
    public string TasksAssembly { get; set; } = "";

    /// System.Resources.Extensions, if referenced. Non-string resources need it.
    public List<string> References { get; set; } = new();

    public List<Resource> Resources { get; set; } = new();
}

internal sealed class Resource
{
    public string Source { get; set; } = "";
    public string Output { get; set; } = "";
}

internal static class Program
{
    private static int Main(string[] args)
    {
        if (args.Length == 1 && args[0] == "cultures")
        {
            return Cultures.Print();
        }

        if (args.Length != 1)
        {
            Console.Error.WriteLine("usage: resx <request.json> | resx cultures");
            return 1;
        }

        var options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true };
        var request = JsonSerializer.Deserialize<Request>(File.ReadAllText(args[0]), options)!;

        try
        {
            Compile(request);
        }
        catch (InvalidOperationException e)
        {
            // A task failed, having logged why, or is missing from this SDK.
            Console.Error.WriteLine($"error: {e.Message}");
            return 1;
        }

        return 0;
    }

    private static void Compile(Request request)
    {
        var tasks = Tasks.Load(request.TasksAssembly);
        var task = Tasks.Create(tasks, new StubBuildEngine(), "Microsoft.Build.Tasks.GenerateResource");

        // As the SDK's CoreResGen target sets them for .NET.
        Tasks.Set(task, "Sources", request.Resources.Select(r => Item(r.Source)).ToArray());
        Tasks.Set(task, "OutputResources", request.Resources.Select(r => Item(r.Output)).ToArray());
        Tasks.Set(task, "References", request.References.Select(Item).ToArray());
        Tasks.Set(task, "UsePreserializedResources", true);

        // A `ResXFileRef` is relative to the `.resx` that names it.
        Tasks.Set(task, "UseSourcePath", true);

        // Out of process would need ResGen.exe, which is .NET Framework only.
        Tasks.SetIfDeclared(task, "ExecuteAsTool", false);

        // Only for MSBuild's incremental builds.
        Tasks.SetIfDeclared(task, "MinimalRebuildFromTracking", false);
        Tasks.SetIfDeclared(task, "TrackFileAccess", false);

        foreach (var resource in request.Resources)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(Path.GetFullPath(resource.Output))!);
        }

        Tasks.Run(task, "GenerateResource");
    }

    private static ITaskItem Item(string path) => new TaskItem(Path.GetFullPath(path));
}

/// The culture names MSBuild's AssignCulture accepts. Bazel needs them before
/// any action runs, so they are kept in cultures.bzl.
internal static class Cultures
{
    // MSBuild accepts these even where the OS does not list them.
    private static readonly string[] PseudoLocales = { "qps-ploc", "qps-ploca", "qps-plocm", "qps-Latn-x-sh" };

    // Names the runtime resolves but does not enumerate, kept if it accepts them.
    private static readonly string[] Aliases =
    {
        "az-AZ-Cyrl", "az-AZ-Latn", "bs-BA-Latn", "en-US-POSIX", "ha-NG-Latn", "in", "iw", "ji", "mn-MN-Mong",
        "no", "sh", "sr-BA-Cyrl", "sr-BA-Latn", "sr-SP-Cyrl", "sr-SP-Latn", "tg-TJ-Cyrl", "tzm-DZ-Latn",
        "uz-UZ-Cyrl", "uz-UZ-Latn", "zh-CHS", "zh-CHT", "zh-CN", "zh-HK", "zh-MO", "zh-SG", "zh-TW",
    };

    public static int Print()
    {
        var enumerated = CultureInfo.GetCultures(CultureTypes.AllCultures)
            .Select(c => c.Name)
            .Where(name => name != "")
            .ToList();

        // Invariant globalization enumerates next to nothing.
        if (enumerated.Count < 500)
        {
            Console.Error.WriteLine($"The runtime lists only {enumerated.Count} cultures. Run this with ICU available.");
            return 1;
        }

        var names = enumerated
            .Concat(PseudoLocales)
            .Concat(Aliases.Where(IsPredefined))
            .Select(name => name.ToLowerInvariant())
            .Distinct()
            .OrderBy(name => name, StringComparer.Ordinal);

        var output = new StringBuilder();
        output.Append("\"\"\"The culture names MSBuild recognises in a resource file name, as in `Strings.fr.resx`.\n\n");
        output.Append("Generated by `bazel run //dotnet/private/tools/resx -- cultures`. Do not edit.\n");
        output.Append("\"\"\"\n\n");
        output.Append("# Lower case: MSBuild compares culture names case-insensitively.\n");
        output.Append("CULTURES = {\n");
        foreach (var name in names)
        {
            output.Append($"    \"{name}\": None,\n");
        }

        output.Append("}\n");
        Console.Out.Write(output.ToString());
        return 0;
    }

    // What MSBuild's CultureInfoCache asks the runtime.
    private static bool IsPredefined(string name)
    {
        try
        {
            CultureInfo.GetCultureInfo(name, predefinedOnly: true);
            return true;
        }
        catch (CultureNotFoundException)
        {
            return false;
        }
    }
}
